package org.lacan.asr.parakeet

import java.io.DataInputStream
import org.junit.Assert.*
import org.junit.Test

class ParakeetFrontendTest {
    @Test fun fullWindowMatchesPinnedGoogleFrontend() { assertUpstream(80_000) }

    @Test fun partialWindowMatchesPinnedGoogleFrontendAndPadsTimeAxis() {
        val actual = assertUpstream(12_345)
        for (mel in 0 until 128) {
            for (frame in 12_345 / 160 until 500) {
                assertEquals("padding [$mel,$frame]", 0f, actual[mel * 500 + frame], 0f)
            }
        }
    }

    @Test fun silenceIsFiniteAndShorterThanTwoFramesIsZero() {
        val frontend = ParakeetFrontend()
        for (size in listOf(0, 1, 159, 160, 319, 320, 80_000)) {
            val features = frontend.process(FloatArray(size))
            assertEquals(64_000, features.size)
            assertTrue("silence length $size", features.all { it.isFinite() })
            // Upstream accumulates means in Float, so long silent windows can have a
            // small normalization residual. Preserve that exact model input behavior.
            if (size < 320) assertTrue(features.all { it == 0f })
        }
    }

    @Test fun rejectsOversizedAndNonFiniteAudio() {
        val frontend = ParakeetFrontend()
        for (samples in listOf(FloatArray(80_001), floatArrayOf(Float.NaN), floatArrayOf(Float.POSITIVE_INFINITY))) {
            assertThrows(IllegalArgumentException::class.java) { frontend.process(samples) }
        }
    }

    private fun assertUpstream(size: Int): FloatArray {
        // Generated by the unmodified pinned Google MelSpectroProcessor and its bundled
        // JLibrosa jar; see resources/parakeet/README.md for provenance and regeneration.
        val audio = FloatArray(size) { i -> (((i * 73) % 997) - 498) / 1024f }
        val actual = ParakeetFrontend().process(audio)
        assertEquals(64_000, actual.size)
        DataInputStream(javaClass.getResourceAsStream("/parakeet/upstream-$size.f32be")!!).use { golden ->
            for (i in actual.indices) {
                assertEquals("feature $i for $size samples", golden.readFloat(), actual[i], 1e-5f)
            }
            assertEquals(-1, golden.read())
        }
        assertArrayEquals("frontend must not mutate audio", FloatArray(size) { i -> (((i * 73) % 997) - 498) / 1024f }, audio, 0f)
        return actual
    }
}
